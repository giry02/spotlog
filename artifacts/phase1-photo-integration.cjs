const assert = require('node:assert/strict');
const { chromium } = require('C:/Users/Giry/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const report = [];
  const log = (name, detail) => { report.push({ name, detail }); console.log(name, JSON.stringify(detail)); };
  const settle = () => page.waitForTimeout(180);
  try {
    await page.goto('http://127.0.0.1:5197/#places-photo', { waitUntil: 'domcontentloaded' });
    await page.getByRole('textbox', { name: '랜드마크 지역 검색' }).fill('협재');
    const card = page.locator('.photo-place-card').filter({ has: page.getByRole('heading', { name: '협재해수욕장', exact: true }) });
    await card.waitFor();
    await card.getByRole('button', { name: '협재해수욕장 다음 사진', exact: true }).click();
    await settle();
    assert.equal(await card.locator('.photo-place-count').innerText(), '2 / 2');
    const bookmark = card.locator('.photo-place-bookmark');
    if (await bookmark.getAttribute('aria-pressed') !== 'true') await bookmark.click();
    assert.equal(await bookmark.getAttribute('aria-pressed'), 'true');
    log('photo swipe and shared save', true);
    await card.scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'C:/Users/Giry/Documents/Spotlog/artifacts/phase1-photo-integrated-390.png' });
    await page.getByRole('button', { name: '지역 안내', exact: true }).click();
    assert.equal(await page.getByRole('textbox', { name: '랜드마크 지역 검색' }).inputValue(), '협재');
    await page.locator('.landmark-guide-card').getByRole('button', { name: '저장됨', exact: true }).waitFor();
    log('guide shares filter and saved state', true);
    await page.getByRole('navigation', { name: '주요 메뉴' }).getByRole('button', { name: '저장', exact: true }).click();
    const savedCard = page.locator('.library-place-card').filter({ has: page.getByRole('heading', { name: '협재해수욕장', exact: true }) });
    await savedCard.waitFor();
    const openPlacement = () => savedCard.locator('.library-add').click();
    await openPlacement();
    await page.getByRole('dialog').waitFor();
    await settle();
    assert.equal(await page.getByRole('combobox', { name: '담을 여행' }).inputValue(), '');
    assert.equal(await page.getByRole('button', { name: '여행과 DAY를 선택하세요', exact: true }).isDisabled(), true);
    log('no implicit trip or day', true);
    await page.screenshot({ path: 'C:/Users/Giry/Documents/Spotlog/artifacts/phase1-trip-sheet-390.png' });
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await settle();
    log('escape restores focus', await savedCard.locator('.library-add').evaluate((element) => element === document.activeElement));
    assert.equal(await savedCard.locator('.library-add').evaluate((element) => element === document.activeElement), true);
    await openPlacement();
    await page.getByRole('dialog').waitFor();
    await settle();
    await page.goBack();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await settle();
    assert.equal(new URL(page.url()).hash, '#saved');
    log('browser back closes only sheet', true);
    await openPlacement();
    await page.getByRole('dialog').getByRole('button', { name: '새 여행 만들기', exact: true }).click();
    await page.getByRole('textbox', { name: '새 여행 이름', exact: true }).fill('사진 탐색 검수 여행');
    await page.getByRole('dialog').getByRole('button', { name: '새 여행 만들기', exact: true }).click();
    await page.getByRole('button', { name: 'DAY 추가', exact: true }).click();
    await page.getByRole('button', { name: 'DAY 2에 담기', exact: true }).click();
    await page.getByRole('dialog').getByText('사진 탐색 검수 여행', { exact: true }).last().waitFor();
    const activeDay = await page.locator('.phase-day-options .active').innerText();
    assert.equal(activeDay, 'DAY 2');
    log('new trip day2 explicit add', true);
    await page.getByRole('dialog').getByRole('button', { name: '닫기', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await settle();
    await page.setViewportSize({ width: 320, height: 740 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await savedCard.scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'C:/Users/Giry/Documents/Spotlog/artifacts/phase1-saved-320.png' });
    await openPlacement();
    await page.getByRole('dialog').waitFor();
    await settle();
    const rect = await page.getByRole('dialog').boundingBox();
    assert.ok(rect.width <= 320 && rect.x >= 0);
    assert.equal(await page.getByRole('combobox', { name: '담을 여행' }).inputValue(), '');
    await page.screenshot({ path: 'C:/Users/Giry/Documents/Spotlog/artifacts/phase1-trip-sheet-320.png' });
    log('320px sheet and save layout', rect);
    assert.deepEqual(errors, []);
    log('uncaught page errors', errors);
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
