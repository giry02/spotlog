const { chromium } = require('C:/Users/Giry/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const out = path.join(__dirname, 'ai-travel-sheet-qa');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const results = [];
  for (const width of [320, 390, 460]) {
    const context = await browser.newContext({ viewport: { width, height: 844 } });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5173/#home');
    await page.waitForSelector('.home-page');
    const before = await page.evaluate(() => JSON.stringify(localStorage));
    await page.evaluate(async () => {
      const React = await import('/node_modules/.vite/deps/react.js');
      const ReactDOM = await import('/node_modules/.vite/deps/react-dom_client.js');
      const { AiTravelSheet } = await import('/src/AiTravelSheet.tsx');
      const { placeCatalog } = await import('/src/data.ts');
      const mount = document.createElement('div'); document.body.append(mount);
      const root = ReactDOM.default.createRoot(mount); window.qaCreated = []; window.qaSaveFail = true;
      root.render(React.default.createElement(AiTravelSheet, { places: placeCatalog, onClose: () => { root.unmount(); mount.remove(); }, onCreate: draft => { if (window.qaSaveFail) return null; window.qaCreated.push(draft); return draft.id; } }));
    });
    const sheet = page.getByRole('dialog'); await sheet.waitFor();
    await page.waitForTimeout(80);
    assert.equal(await sheet.getByRole('button', { name: '초안 만들기', exact: true }).isDisabled(), true);
    await sheet.getByLabel('어떤 여행을 하고 싶으세요?').fill('도쿄 3일');
    await sheet.getByRole('button', { name: '초안 만들기', exact: true }).click();
    await sheet.getByRole('alert').waitFor();
    assert.match(await sheet.getByRole('alert').innerText(), /지역/);
    await sheet.getByLabel('어떤 여행을 하고 싶으세요?').fill('부산 1박2일 바다 보고 카페는 빼고 덜 걷고 싶어요');
    await sheet.locator('.phase-sheet-body').evaluate(el => el.scrollTop = 0);
    await page.screenshot({ path: path.join(out, `${width}-input.png`) });
    await sheet.getByRole('button', { name: '초안 만들기', exact: true }).click();
    await sheet.getByRole('heading', { name: '여행 초안 미리보기', exact: true }).waitFor();
    assert.equal(await sheet.locator('.ai-travel-day').count(), 2);
    await sheet.locator('.phase-sheet-body').evaluate(el => el.scrollTop = 0);
    await page.screenshot({ path: path.join(out, `${width}-preview.png`) });
    await sheet.getByRole('button', { name: '이 초안으로 내 여행 만들기' }).click();
    await sheet.getByRole('alert').waitFor();
    assert.match(await sheet.getByRole('alert').innerText(), /저장하지 못/);
    await sheet.getByRole('button', { name: '조건 바꾸기' }).click();
    await sheet.getByLabel('어떤 여행을 하고 싶으세요?').fill('서울 6박7일');
    await sheet.getByRole('button', { name: '초안 만들기', exact: true }).click();
    assert.equal(await sheet.locator('.ai-travel-day').count(), 7);
    assert.ok(await sheet.getByText('장소가 부족해 비워 두었어요. 내 여행에서 추가해 주세요.').count() > 0);
    const metrics = await sheet.evaluate(el => ({ width: el.getBoundingClientRect().width, bodyOverflow: el.querySelector('.phase-sheet-body').scrollWidth > el.querySelector('.phase-sheet-body').clientWidth, documentOverflow: document.documentElement.scrollWidth > innerWidth }));
    assert.equal(metrics.bodyOverflow, false); assert.equal(metrics.documentOverflow, false);
    await page.evaluate(() => window.qaSaveFail = false);
    await sheet.getByRole('button', { name: '이 초안으로 내 여행 만들기' }).click();
    await sheet.waitFor({ state: 'detached' });
    const created = await page.evaluate(() => window.qaCreated);
    assert.equal(created.length, 1); assert.equal(created[0].days.length, 7); assert.equal(created[0].visibility, 'PRIVATE'); assert.equal(created[0].recommendationKind, 'AI');
    assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), before);
    assert.deepEqual(errors, []);
    results.push({ width, metrics, created: created.length, localStorageUnchanged: true, errors });
    await context.close();
  }
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify(results, null, 2));
  await browser.close(); console.log(JSON.stringify(results));
})().catch(error => { console.error(error); process.exit(1); });
