import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Explicit local facts only. No network, app-source import, runtime settings or
// existing registered snapshot is read or changed by this generator.
const input = new URL('../lib/jeju-registered-businesses.json', import.meta.url);
const output = new URL('../lib/jeju-registered-businesses.ts', import.meta.url);
const expectedIds = new Map([
  ['catalog-jeju-hyeopjae-sin-guksu', 'FOOD'],
  ['catalog-jeju-myeongri-main', 'FOOD'],
  ['catalog-jeju-bongseong', 'FOOD'],
  ['catalog-jeju-paratodos', 'CAFE'],
  ['catalog-jeju-coffee-sketch', 'CAFE'],
  ['catalog-jeju-landing-shinhwa', 'STAY'],
]);
const ownKeys = (value, keys) => value && typeof value === 'object' && !Array.isArray(value)
  && Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key));
const nonempty = value => typeof value === 'string' && value.trim().length > 0;
const fail = message => { throw new Error(`Invalid local Jeju catalog: ${message}`); };

export function validateJejuRegisteredCatalog(data) {
  if (!ownKeys(data, ['importedAt', 'source', 'sourceFiles', 'scope', 'entries'])
      || data.importedAt !== '2026-10-22' || !nonempty(data.source)
      || data.scope !== 'name-address-category-coordinate-original-editorial-description'
      || !Array.isArray(data.sourceFiles) || data.sourceFiles.length !== 1
      || data.sourceFiles[0] !== 'lib/jeju-registered-businesses.json'
      || !Array.isArray(data.entries) || data.entries.length !== expectedIds.size) fail('snapshot metadata');
  const seen = new Set();
  for (const item of data.entries) {
    if (!ownKeys(item, ['id', 'kind', 'name', 'area', 'address', 'latitude', 'longitude', 'description', 'note', 'tags', 'duration', 'source', 'photos', 'price', 'openingHours', 'availability'])
        || expectedIds.get(item.id) !== item.kind || seen.has(item.id)) fail('stable identity');
    seen.add(item.id);
    if (!['name', 'area', 'address', 'description', 'note'].every(key => nonempty(item[key]))
        || !item.area.startsWith('제주 ') || !item.address.startsWith('제주특별자치도 ')
        || typeof item.duration !== 'string' || !Array.isArray(item.tags)
        || item.tags.some(tag => !nonempty(tag))) fail(`editorial facts: ${item.id}`);
    if (!Number.isFinite(item.latitude) || item.latitude < 33.1 || item.latitude > 33.6
        || !Number.isFinite(item.longitude) || item.longitude < 126 || item.longitude > 127) fail(`coordinate: ${item.id}`);
    if (!ownKeys(item.source, ['provider', 'providerRecordId', 'sourceUrl', 'checkedAt', 'coordinateReference', 'scope'])
        || item.source.provider !== '제주관광공사 VisitJeju'
        || !/^CNTS_[A-Za-z0-9_]+$/.test(item.source.providerRecordId)
        || item.source.sourceUrl !== `https://www.visitjeju.net/kr/detail/view?contentsid=${item.source.providerRecordId}`
        || item.source.checkedAt !== data.importedAt
        || item.source.coordinateReference !== '공식 관광 상세 지도 대표 지점'
        || item.source.scope !== 'name-address-category-coordinate') fail(`source provenance: ${item.id}`);
    if (!Array.isArray(item.photos) || item.photos.length || item.price !== null
        || item.openingHours !== null || item.availability !== null) fail(`unverified live facts: ${item.id}`);
  }
  return data;
}

export function generatedJejuRegisteredCatalog(data) {
  validateJejuRegisteredCatalog(data);
  return '// Generated by scripts/sync-jeju-registered-catalog.mjs from the independent local Jeju supplement.\n'
    + '// The original Spotlog app snapshot and fictional demo identities remain separate.\n'
    + 'const snapshot = ' + JSON.stringify(data, null, 2) + ';\nexport default snapshot;\n';
}

async function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) fail('unsupported argument');
  const data = JSON.parse(await readFile(input, 'utf8'));
  const generated = generatedJejuRegisteredCatalog(data);
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== generated) fail('generated TypeScript is stale; run this script without --check');
    console.log(`Jeju supplement is synchronized: ${data.entries.length} verified records.`);
  } else {
    await writeFile(output, generated, 'utf8');
    console.log(`Synchronized ${data.entries.length} Jeju records. Existing app snapshot preserved.`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
