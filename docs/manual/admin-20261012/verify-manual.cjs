const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('C:/Users/Giry/.codex/worktrees/a125/Spotlog/node_modules/@playwright/test');
const root = __dirname;
const base = 'http://127.0.0.1:5210/@fs/C:/Users/Giry/Documents/Spotlog/docs/manual/admin-20261012/index.html';
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manual-data.json'), 'utf8'));
const checks = [];
const errors = [];
function check(name, okay, detail = '') { checks.push({ name, okay: !!okay, detail }); if (!okay) throw new Error(name + ': ' + detail); }
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    const response = await page.goto(base); check('local HTML response', response.status() === 200, response.status());
    await page.locator('#manual-search-state').filter({ hasText: '처음 사용하기' }).waitFor();
    check('default quick start', await page.locator('#quickstart').isVisible());
    const counts = await page.evaluate(() => ({ pages: document.querySelectorAll('.guide-page').length, markers: document.querySelectorAll('.guide-shot .guide-marker').length, rows: document.querySelectorAll('.guide-callout').length, missing: [...document.querySelectorAll('[aria-controls]')].filter(el => !document.getElementById(el.getAttribute('aria-controls'))).length }));
    check('complete screenshots', counts.pages === manifest.pages.length, JSON.stringify(counts));
    check('number to description mapping', counts.markers === counts.rows && counts.missing === 0, JSON.stringify(counts));
    const loaded = await page.evaluate(async () => {
      const pages = JSON.parse(document.getElementById('manual-data').textContent);
      return await Promise.all(pages.map(p => new Promise(resolve => { const img = new Image(); img.onload = () => resolve({ id: p.id, okay: img.naturalWidth === p.width && img.naturalHeight === p.height }); img.onerror = () => resolve({ id: p.id, okay: false }); img.src = p.image; })));
    });
    check('all image files decode with expected dimensions', loaded.every(result => result.okay), JSON.stringify(loaded.filter(result => !result.okay)));
    for (const menu of manifest.menus) {
      await page.locator(`.guide-nav nav [data-menu-link="${menu.id}"]`).click();
      const visible = await page.locator('.guide-page:visible').evaluateAll(elements => elements.map(el => el.id));
      const expected = manifest.pages.filter(p => p.menu === menu.id).map(p => p.id);
      check('menu ' + menu.name, JSON.stringify(visible) === JSON.stringify(expected), visible.join(','));
    }
    for (const term of ['메인', '좌표', '색인']) {
      await page.locator('#manual-search').fill(term);
      check('search ' + term, (await page.locator('.guide-page:visible').count()) > 0);
      check('search hides quick start ' + term, !(await page.locator('#quickstart').isVisible()));
    }
    await page.locator('#manual-search').fill('없는기능xyz');
    check('empty search feedback', await page.locator('#manual-no-results').isVisible());
    await page.locator('#manual-search-clear').click();
    check('clear search', (await page.locator('#manual-search').inputValue()) === '');
    await page.locator('.guide-nav nav [data-menu-link="places"]').click();
    await page.locator('#manual-contents a').filter({ hasText: '장소 등록 · 기본 정보' }).click();
    await page.locator('#place-basic .guide-marker').first().click();
    check('number highlights definition', await page.locator('#place-basic-callout-1').evaluate(el => el.classList.contains('is-active')));
    await page.locator('#place-basic [data-enlarge]').first().click();
    check('screenshot viewer opens', await page.locator('#manual-viewer').evaluate(el => el.open));
    await page.locator('#manual-zoom-canvas .guide-marker').nth(1).click();
    check('viewer number explains feature', (await page.locator('#manual-zoom-details h3').textContent()).startsWith('2.'));
    await page.locator('#manual-zoom-original').click();
    check('original screenshot size', (await page.locator('#manual-zoom-ratio').textContent()) === '100%');
    await page.locator('#manual-zoom-in').click();
    check('zoom in', (await page.locator('#manual-zoom-ratio').textContent()) === '115%');
    await page.locator('#manual-zoom-out').click();
    check('zoom out', (await page.locator('#manual-zoom-ratio').textContent()) === '100%');
    await page.locator('#manual-zoom-fit').click();
    await page.keyboard.press('Escape');
    check('Escape closes viewer', !(await page.locator('#manual-viewer').evaluate(el => el.open)));
    check('viewer returns keyboard focus', await page.locator('#place-basic [data-enlarge]').first().evaluate(el => el === document.activeElement));
    await page.locator('#place-basic img').evaluate(img => { img.loading = 'eager'; return img.decode(); });
    await page.locator('#place-basic').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
    await page.screenshot({ path: path.join(root, 'qa-places-desktop.png') });
    await page.locator('.guide-nav nav [data-menu-link="start"]').click();
    await page.screenshot({ path: path.join(root, 'qa-start-desktop.png') });
    check('desktop no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('.guide-nav nav [data-menu-link="exposure"]').click();
    await page.locator('#main-post img').evaluate(img => { img.loading = 'eager'; return img.decode(); });
    await page.locator('#main-post').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
    check('wide screenshot remains readable', await page.locator('#main-post img').evaluate(img => img.getBoundingClientRect().width > 1000));
    await page.screenshot({ path: path.join(root, 'qa-main-post-desktop.png') });
    await page.goto(base + '#ai-indices');
    await page.locator('.guide-nav nav [data-menu-link="ai"][aria-current="page"]').waitFor();
    check('deep link selects correct menu', (await page.locator('.guide-nav nav [aria-current="page"]').getAttribute('data-menu-link')) === 'ai');
    check('deep link screenshot visible', await page.locator('#ai-indices').isVisible());
    await page.goto(base + '#%E0%ZZ');
    await page.locator('#quickstart').waitFor();
    check('invalid deep link recovers', await page.locator('#quickstart').isVisible());
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.locator('.guide-nav nav [data-menu-link="places"]').click();
    await page.locator('#place-basic img').evaluate(img => { img.loading = 'eager'; return img.decode(); });
    await page.locator('#place-basic').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
    await page.screenshot({ path: path.join(root, 'qa-places-wide.png') });
    check('wide no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.guide-nav nav [data-menu-link="start"]').click();
    await page.screenshot({ path: path.join(root, 'qa-start-mobile.png') });
    check('mobile no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    check('mobile toolbar labels stay on one line', await page.locator('.guide-tools > .guide-button').evaluateAll(buttons => buttons.every(button => button.getBoundingClientRect().height < 60)));
    await page.locator('.guide-nav nav [data-menu-link="places"]').click();
    await page.locator('#place-basic').scrollIntoViewIfNeeded();
    check('mobile screenshot no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('#place-basic [data-enlarge]').first().click();
    await page.locator('#manual-zoom-original').click();
    check('mobile zoom scroll contained', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(root, 'qa-viewer-mobile.png') });
    await page.locator('#manual-viewer-close').click();
    await context.close();
    const offline = await browser.newContext();
    const localPage = await offline.newPage();
    const network = [];
    localPage.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
    localPage.on('pageerror', error => errors.push(error.message));
    await localPage.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await localPage.locator('#manual-search-state').filter({ hasText: '처음 사용하기' }).waitFor();
    await localPage.locator('.guide-nav nav [data-menu-link="places"]').click();
    await localPage.locator('#manual-search').fill('사진');
    check('offline search works', (await localPage.locator('.guide-page:visible').count()) > 0);
    const offlineImage = await localPage.locator('.guide-page:visible img').first().evaluate(async img => { img.loading = 'eager'; await img.decode(); return img.naturalWidth > 0; });
    check('offline screenshot works', offlineImage);
    check('offline requires no network', network.length === 0, network.join(','));
    const standalonePage = await offline.newPage();
    const standaloneRequests = [];
    standalonePage.on('request', request => { if (!request.url().startsWith('data:')) standaloneRequests.push(request.url()); });
    standalonePage.on('pageerror', error => errors.push(error.message));
    await standalonePage.goto(pathToFileURL(path.join(root, 'spotlog-admin-manual.html')).href);
    await standalonePage.locator('#manual-search-state').filter({ hasText: '처음 사용하기' }).waitFor();
    await standalonePage.locator('.guide-nav nav [data-menu-link="exposure"]').click();
    const inlineScreenshot = await standalonePage.locator('#main-post img').evaluate(async img => { img.loading = 'eager'; await img.decode(); return img.src.startsWith('data:image/png;') && img.naturalWidth > 0; });
    check('single HTML embeds real screenshot', inlineScreenshot);
    await standalonePage.locator('#main-post').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
    await standalonePage.locator('#main-post [data-enlarge]').first().click();
    const inlineViewer = await standalonePage.locator('#manual-zoom-canvas img').evaluate(async img => { await img.decode(); return img.src.startsWith('data:image/png;') && img.naturalWidth > 0; });
    check('single HTML zoom uses embedded screenshot', inlineViewer);
    await standalonePage.locator('#manual-viewer-close').click();
    check('single HTML loads no sibling files', standaloneRequests.length === 1 && standaloneRequests[0].endsWith('spotlog-admin-manual.html'), JSON.stringify(standaloneRequests));
    check('browser errors', errors.length === 0, errors.join('\n'));
    await offline.close();
  } finally { await browser.close(); }
  fs.writeFileSync(path.join(root, 'verification.json'), JSON.stringify({ verified: new Date().toISOString(), screenshots: manifest.pages.length, numberedFeatures: manifest.pages.reduce((n,p) => n+p.callouts.length,0), checks, errors }, null, 2) + '\n');
  console.log(JSON.stringify({ okay: checks.filter(result => result.okay).length, total: checks.length, errors }));
})().catch(error => { console.error(error); process.exitCode = 1; });
